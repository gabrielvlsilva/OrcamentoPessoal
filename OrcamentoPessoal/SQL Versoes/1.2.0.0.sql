CREATE TABLE `trn` (
    `TRN_AIC` INT UNSIGNED NOT NULL AUTO_INCREMENT,
    `USR_AIC` INT UNSIGNED NOT NULL,
    `DOC_AIC` INT UNSIGNED NOT NULL,
    `TRN_DES` VARCHAR(150) NOT NULL,
    `TRN_VAL` DECIMAL(15,2) NOT NULL,
    `TRN_DTA` DATE NULL,
    `TRN_TIP` TINYINT UNSIGNED NOT NULL COMMENT '1 = Receita; 2 = Despesa',
    `TRN_CAT` VARCHAR(40) NOT NULL,
    `TRN_FPG` VARCHAR(100) NOT NULL DEFAULT '',
    `TRN_STA` TINYINT UNSIGNED NOT NULL DEFAULT 2 COMMENT '1 = Pendente; 2 = Concluído; 3 = Cancelado',
    `TRN_CNF` DECIMAL(5,4) NOT NULL DEFAULT 0,
    `TRN_PAG` INT UNSIGNED NULL,
    `TRN_PLA` VARCHAR(255) NULL,
    `TRN_LIN` INT UNSIGNED NULL,
    `TRN_DTC` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (`TRN_AIC`),
    KEY `IX_TRN_USR_DTA` (`USR_AIC`, `TRN_DTA`),
    KEY `IX_TRN_DOC` (`DOC_AIC`),
    CONSTRAINT `FK_TRN_USR` FOREIGN KEY (`USR_AIC`)
        REFERENCES `usr` (`USR_AIC`),
    CONSTRAINT `FK_TRN_DOC` FOREIGN KEY (`DOC_AIC`)
        REFERENCES `doc` (`DOC_AIC`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
