CREATE TABLE `doc` (
    `DOC_AIC` INT UNSIGNED NOT NULL AUTO_INCREMENT,
    `USR_AIC` INT UNSIGNED NOT NULL,
    `DOC_NOM` VARCHAR(255) NOT NULL,
    `DOC_EXT` VARCHAR(10) NOT NULL,
    `DOC_TAM` BIGINT UNSIGNED NOT NULL,
    `DOC_ID` CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    `DOC_STA` VARCHAR(30) NOT NULL DEFAULT 'Recebido',
    `DOC_DTU` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (`DOC_AIC`),
    UNIQUE KEY `UQ_DOC_ID` (`DOC_ID`),
    KEY `IX_DOC_USR_DTU` (`USR_AIC`, `DOC_DTU`),
    CONSTRAINT `FK_DOC_USR` FOREIGN KEY (`USR_AIC`)
        REFERENCES `usr` (`USR_AIC`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
